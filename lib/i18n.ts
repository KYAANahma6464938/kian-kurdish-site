export type Dict = (typeof dictionaries)['fa']

export function getDict(lang: Language): Dict {
  return dictionaries[lang] as Dict
}

/** Pick the chat language automatically from the user's text. */
export function detectLanguage(text: string): Language {
  const persian = /[\u0600-\u06FF]/
  return persian.test(text) ? 'fa' : 'en'
}
